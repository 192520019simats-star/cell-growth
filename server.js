// Simple Express server: serves everything inside /public on localhost.
const express = require('express');
const path = require('path');

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.static(path.join(__dirname, 'public')));

// Fallback so any unknown path returns the single-page app
app.use((req, res) => {
  res.sendFile(path.join(__dirname, 'public', 'index.html'));
});

app.listen(PORT, () => {
  console.log(`Cell Growth Explorer running at http://localhost:${PORT}`);
});
